// --------------------------------------------------------------------------
// SMS Tours Master Store Synchronization Engine (API + localStorage fallback)
// --------------------------------------------------------------------------
const SMS_STORE_KEY = 'sms_tours_store_v1';

// Synchronize memory arrays from stored JSON
function applyStoreData(store) {
  if (!store) return;
  if (Array.isArray(store.tourPackages) && store.tourPackages.length > 0) {
    tourPackages = store.tourPackages;
  }
  if (Array.isArray(store.galleryItems) && store.galleryItems.length > 0) {
    galleryItems = store.galleryItems;
  }
  if (Array.isArray(store.blogs) && store.blogs.length > 0 && typeof companyInfo !== 'undefined') {
    companyInfo.blogs = store.blogs;
  }
  if (Array.isArray(store.tourStories) && store.tourStories.length > 0) {
    tourStories = store.tourStories;
  }
  if (typeof window !== 'undefined') {
    window.tourPackages = tourPackages;
    window.galleryItems = galleryItems;
    window.tourStories = tourStories;
    window.companyInfo = companyInfo;
  }
}

// Export current store state
function getCurrentStoreData() {
  return {
    tourPackages: tourPackages,
    galleryItems: galleryItems,
    blogs: (typeof companyInfo !== 'undefined' && companyInfo.blogs) ? companyInfo.blogs : [],
    tourStories: (typeof tourStories !== 'undefined') ? tourStories : []
  };
}

// Load data on startup with Netlify & static fallback support
async function syncAndLoadStore() {
  // 1. Try local storage first for instant load
  try {
    const local = localStorage.getItem(SMS_STORE_KEY);
    if (local) {
      applyStoreData(JSON.parse(local));
    }
  } catch (e) {
    console.warn('localStorage read error:', e);
  }

  // 2. Fetch fresh store from /api/data or static data/store.json (Netlify)
  try {
    let serverData = null;

    // A. Try API endpoint (Local server or Netlify Function)
    try {
      const res = await fetch('/api/data');
      if (res.ok) {
        const ct = res.headers.get('content-type') || '';
        if (ct.includes('json')) {
          serverData = await res.json();
        }
      }
    } catch (_) {
      // API not available, proceed to static fallback
    }

    // B. Static fallback directly to data/store.json (for Netlify static deploy)
    if (!serverData) {
      try {
        const resStatic = await fetch('data/store.json');
        if (resStatic.ok) {
          const ct = resStatic.headers.get('content-type') || '';
          if (ct.includes('json') || !ct.includes('html')) {
            serverData = await resStatic.json();
          }
        }
      } catch (_) {}
    }

    if (serverData && typeof serverData === 'object') {
      const local = localStorage.getItem(SMS_STORE_KEY);
      if (!local) {
        applyStoreData(serverData);
        localStorage.setItem(SMS_STORE_KEY, JSON.stringify(serverData));
      }
    }
  } catch (err) {
    console.log('Running in client-only mode or offline:', err.message);
  }
}

// Save data to server & localStorage
async function persistStoreData(storePayload) {
  applyStoreData(storePayload);
  
  // 1. Local storage save (always persists immediately in browser)
  let localSaved = false;
  try {
    localStorage.setItem(SMS_STORE_KEY, JSON.stringify(storePayload));
    localSaved = true;
  } catch (e) {
    console.warn('localStorage write error:', e);
  }

  // 2. Server API save (for Node server or Netlify Function)
  let apiSaved = false;
  try {
    const res = await fetch('/api/save', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(storePayload)
    });
    if (res.ok) {
      apiSaved = true;
    }
  } catch (err) {
    // Normal on static host without Node server
  }

  return localSaved || apiSaved;
}

// Initial sync call
syncAndLoadStore();

